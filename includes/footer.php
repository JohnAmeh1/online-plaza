<script>
    // Global variables
    let deferredPrompt = null;
    let installAvailable = false;

    // Get button elements
    const installBtn = document.getElementById('install-martly-btn');
    const mobileBadge = document.getElementById('pwa-install-badge');

    console.log('PWA Script Loaded - Buttons found:', {
        installBtn: !!installBtn,
        mobileBadge: !!mobileBadge
    });

    // Function to trigger browser's install prompt
    async function triggerBrowserInstall() {
        console.log('Triggering browser install prompt...');

        // Method 1: Use beforeinstallprompt event if available
        if (deferredPrompt) {
            console.log('Using deferred prompt');
            deferredPrompt.prompt();
            const {
                outcome
            } = await deferredPrompt.userChoice;
            console.log(`User ${outcome} the installation`);

            if (outcome === 'accepted') {
                showToast('🎉 Martly installed successfully!', 'success');
                hideInstallButtons();
            }

            deferredPrompt = null;
            return;
        }

        // Method 2: Try to trigger the browser's install UI directly
        if (window.deferredPrompt) {
            window.deferredPrompt.prompt();
            return;
        }

        // Method 3: For browsers that support the install button in address bar
        // This simulates the conditions that make browsers show the install button
        triggerInstallConditions();

        // Method 4: Show instructions for manual installation
        showInstallInstructions();
    }

    // Function to trigger conditions that make browsers show install button
    function triggerInstallConditions() {
        console.log('Triggering install conditions...');

        // Simulate user engagement (required for install prompt)
        simulateUserEngagement();

        // Check and log PWA status
        checkPWAStatus();

        // Show toast to guide user to browser's install button
        showToast('🔧 Look for the install icon (📥) in your browser\'s address bar!', 'info', 6000);

        // For some browsers, we need to wait a bit and check again
        setTimeout(() => {
            if (!installAvailable) {
                console.log('Browser install prompt not triggered automatically');
                // The install button should appear in address bar after user interaction
            }
        }, 1000);
    }

    // Simulate user engagement to trigger browser install prompt
    function simulateUserEngagement() {
        console.log('Simulating user engagement...');

        // Trigger scroll event (common engagement metric)
        window.dispatchEvent(new Event('scroll'));

        // Trigger mouse movement
        document.dispatchEvent(new MouseEvent('mousemove', {
            view: window,
            bubbles: true,
            cancelable: true
        }));

        // Trigger touch event for mobile
        document.dispatchEvent(new TouchEvent('touchstart', {
            view: window,
            bubbles: true,
            cancelable: true
        }));
    }

    // Function to show installation instructions with browser-specific guidance
    function showInstallInstructions() {
        console.log('Showing browser-specific install instructions');

        const browserInfo = detectBrowser();
        let instructions = '';

        switch (browserInfo.name) {
            case 'chrome':
                instructions = `
                <strong>Chrome:</strong>
                <ol style="text-align: left; margin: 10px 0; padding-left: 20px;">
                    <li>Look for the <strong>install icon (📥)</strong> in the address bar</li>
                    <li>Click the install icon</li>
                    <li>Confirm installation when prompted</li>
                    <li><em>If no icon appears, try refreshing the page</em></li>
                </ol>
            `;
                break;

            case 'firefox':
                instructions = `
                <strong>Firefox:</strong>
                <ol style="text-align: left; margin: 10px 0; padding-left: 20px;">
                    <li>Look for the <strong>install icon (➕)</strong> in the address bar</li>
                    <li>Click "Install"</li>
                    <li>Or go to Menu → "Apps" → "Install Martly"</li>
                </ol>
            `;
                break;

            case 'safari':
                instructions = `
                <strong>Safari:</strong>
                <ol style="text-align: left; margin: 10px 0; padding-left: 20px;">
                    <li>Tap the <strong>share icon (📤)</strong> </li>
                    <li>Scroll down and tap "Add to Home Screen"</li>
                    <li>Tap "Add" to confirm</li>
                </ol>
            `;
                break;

            case 'edge':
                instructions = `
                <strong>Microsoft Edge:</strong>
                <ol style="text-align: left; margin: 10px 0; padding-left: 20px;">
                    <li>Look for the <strong>install icon (📥)</strong> in the address bar</li>
                    <li>Click "Install"</li>
                    <li>Or go to Menu → "Apps" → "Install this site as an app"</li>
                </ol>
            `;
                break;

            default:
                instructions = `
                <strong>Your Browser:</strong>
                <ul style="text-align: left; margin: 10px 0; padding-left: 20px;">
                    <li>Look for an <strong>install icon in the address bar</strong></li>
                    <li>Common icons: 📥, ➕, or the browser's app icon</li>
                    <li>Click the icon and follow the prompts</li>
                    <li><em>Refresh the page if you don't see the install option</em></li>
                </ul>
            `;
        }

        const modal = document.createElement('div');
        modal.innerHTML = `
        <div style="position: fixed; top: 0; left: 0; right: 0; bottom: 0; background: rgba(0,0,0,0.5); z-index: 10000; display: flex; align-items: center; justify-content: center; padding: 20px;">
            <div style="background: white; border-radius: 16px; padding: 24px; max-width: 450px; width: 100%; box-shadow: 0 20px 60px rgba(0,0,0,0.3);">
                <div style="display: flex; align-items: center; margin-bottom: 16px;">
                    <div style="width: 48px; height: 48px; background: linear-gradient(135deg, #10b981, #3b82f6); border-radius: 12px; display: flex; align-items: center; justify-content: center; margin-right: 12px;">
                        <i class="fas fa-desktop" style="color: white; font-size: 1.2rem;"></i>
                    </div>
                    <div>
                        <h3 style="margin: 0; color: #1f2937; font-size: 1.25rem; font-weight: 600;">Install Martly</h3>
                        <p style="margin: 4px 0 0 0; color: #6b7280; font-size: 0.9rem;">Using ${browserInfo.name.charAt(0).toUpperCase() + browserInfo.name.slice(1)}</p>
                    </div>
                </div>
                <div style="color: #6b7280; line-height: 1.6; margin-bottom: 24px;">
                    <p style="margin: 0 0 12px 0;">To install Martly as an app:</p>
                    ${instructions}
                    <div style="background: #f3f4f6; padding: 12px; border-radius: 8px; margin-top: 12px;">
                        <p style="margin: 0; font-size: 0.9rem;"><strong>Tip:</strong> The install option usually appears after interacting with the site. Our button helps trigger this!</p>
                    </div>
                </div>
                <div style="display: flex; gap: 12px;">
                    <button onclick="location.reload()" style="flex: 1; padding: 12px; background: #6b7280; color: white; border: none; border-radius: 10px; font-weight: 600; cursor: pointer;">
                        Refresh Page
                    </button>
                    <button onclick="this.closest('div').parentElement.remove()" style="flex: 1; padding: 12px; background: #10b981; color: white; border: none; border-radius: 10px; font-weight: 600; cursor: pointer;">
                        Got It
                    </button>
                </div>
            </div>
        </div>
    `;
        document.body.appendChild(modal);
    }

    // Detect user's browser
    function detectBrowser() {
        const userAgent = navigator.userAgent.toLowerCase();

        if (userAgent.includes('chrome') && !userAgent.includes('edg')) {
            return {
                name: 'chrome',
                version: userAgent.match(/chrome\/(\d+)/)?.[1]
            };
        } else if (userAgent.includes('firefox')) {
            return {
                name: 'firefox',
                version: userAgent.match(/firefox\/(\d+)/)?.[1]
            };
        } else if (userAgent.includes('safari') && !userAgent.includes('chrome')) {
            return {
                name: 'safari',
                version: userAgent.match(/version\/(\d+)/)?.[1]
            };
        } else if (userAgent.includes('edg')) {
            return {
                name: 'edge',
                version: userAgent.match(/edg\/(\d+)/)?.[1]
            };
        } else {
            return {
                name: 'unknown',
                version: 'unknown'
            };
        }
    }

    // Function to show toast messages
    function showToast(message, type = 'info', duration = 5000) {
        // Remove existing toasts
        const existingToasts = document.querySelectorAll('[data-toast]');
        existingToasts.forEach(toast => toast.remove());

        const toast = document.createElement('div');
        toast.setAttribute('data-toast', 'true');
        toast.style.cssText = `
        position: fixed;
        top: 20px;
        right: 20px;
        background: ${type === 'success' ? '#10B981' : type === 'warning' ? '#F59E0B' : '#4F46E5'};
        color: white;
        padding: 16px 20px;
        border-radius: 12px;
        box-shadow: 0 10px 25px rgba(0,0,0,0.2);
        z-index: 10000;
        max-width: 400px;
        font-weight: 500;
        animation: slideIn 0.3s ease-out;
    `;

        // Add CSS for animation
        if (!document.querySelector('#toast-styles')) {
            const styles = document.createElement('style');
            styles.id = 'toast-styles';
            styles.textContent = `
            @keyframes slideIn {
                from { transform: translateX(100%); opacity: 0; }
                to { transform: translateX(0); opacity: 1; }
            }
        `;
            document.head.appendChild(styles);
        }

        toast.textContent = message;
        document.body.appendChild(toast);

        setTimeout(() => {
            if (toast.parentNode) {
                toast.parentNode.removeChild(toast);
            }
        }, duration);
    }

    // Function to hide install buttons
    function hideInstallButtons() {
        if (installBtn) installBtn.style.display = 'none';
        if (mobileBadge) mobileBadge.style.display = 'none';
    }

    // Check if app is already installed
    function isAppInstalled() {
        return window.matchMedia('(display-mode: standalone)').matches ||
            window.navigator.standalone === true;
    }

    // Set up event listeners
    document.addEventListener('DOMContentLoaded', function() {
        console.log('DOM Content Loaded - Setting up install buttons');

        // Hide if already installed
        if (isAppInstalled()) {
            console.log('App is already installed - hiding buttons');
            hideInstallButtons();
            return;
        }

        // Add click event listeners
        if (installBtn) {
            installBtn.addEventListener('click', triggerBrowserInstall);
            console.log('Added click listener to install button');
        }

        if (mobileBadge) {
            mobileBadge.addEventListener('click', triggerBrowserInstall);
            console.log('Added click listener to mobile badge');
        }

        // Check PWA status
        checkPWAStatus();
    });

    // Listen for beforeinstallprompt event
    window.addEventListener('beforeinstallprompt', (e) => {
        console.log('🎉 beforeinstallprompt event fired! PWA is installable');
        e.preventDefault();
        deferredPrompt = e;
        installAvailable = true;

        // Show success toast
        showToast('✅ Martly can be installed! Click the install button.', 'success', 4000);

        // Enable buttons
        if (installBtn) {
            installBtn.disabled = false;
            installBtn.style.opacity = '1';
            installBtn.innerHTML = '<i class="fas fa-download"></i><span>Install Now</span>';
        }
    });

    // Listen for app installed event
    window.addEventListener('appinstalled', (evt) => {
        console.log('🎉 Martly app was installed successfully!');
        deferredPrompt = null;
        installAvailable = false;
        hideInstallButtons();
        showToast('🎉 Martly installed successfully! Find it in your applications.', 'success', 5000);
    });

    // Check PWA status
    function checkPWAStatus() {
        console.log('Checking PWA status...');
        console.log('HTTPS:', window.location.protocol === 'https:');
        console.log('Service Worker:', !!navigator.serviceWorker.controller);
        console.log('Manifest:', !!document.querySelector('link[rel="manifest"]'));
        console.log('Browser:', detectBrowser().name);
    }

    // Service Worker Registration
    if ('serviceWorker' in navigator) {
        window.addEventListener('load', function() {
            navigator.serviceWorker.register('/online-plaza/sw.js')
                .then(function(registration) {
                    console.log('Service Worker registered successfully:', registration.scope);
                })
                .catch(function(error) {
                    console.log('Service Worker registration failed:', error);
                });
        });
    }

    // Make install function globally available
    window.installMartly = triggerBrowserInstall;
    window.triggerBrowserInstall = triggerBrowserInstall;

    // Add a global function to check installability
    window.checkInstallStatus = function() {
        console.log('Install Status Check:');
        console.log('- Deferred Prompt:', !!deferredPrompt);
        console.log('- Install Available:', installAvailable);
        console.log('- App Installed:', isAppInstalled());
        console.log('- Browser:', detectBrowser().name);
    };
</script>



